/** Texto da terceira dica: direção e distância (em passos) de um ponto conhecido do mapa. */
export function relicBearing(r: RelicDef, zone: { x: number; z: number }): string {
  const dx = r.x - zone.x;
  const dz = r.z - zone.z;
  const dist = Math.max(5, Math.round(Math.hypot(dx, dz) / 5) * 5);
  const ang = (Math.atan2(dx, -dz) * 180) / Math.PI; // 0 = norte (−z), 90 = leste (+x)
  const names = ["norte", "nordeste", "leste", "sudeste", "sul", "sudoeste", "oeste", "noroeste"];
  const dir = names[(Math.round((ang < 0 ? ang + 360 : ang) / 45) % 8 + 8) % 8];
  const m = /^(a|as|o|os) (.+)$/.exec(r.near.label);
  const of = m ? `${{ a: "da", as: "das", o: "do", os: "dos" }[m[1] as "a" | "as" | "o" | "os"]} ${m[2]}` : `de ${r.near.label}`;
  return `Cave a cerca de ${dist} passos ao ${dir} ${of}. Procure o brilho de leve no chão.`;
}
